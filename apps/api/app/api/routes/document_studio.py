def _draw_recipient_panel(c: canvas.Canvas, payload: LetterheadDocument, y_top: float) -> float:
    width, _ = A4
    left = 18 * mm
    right = width - 18 * mm
    panel_height = 36 * mm
    panel_bottom = y_top - panel_height

    c.setFillColor(PALE_BLUE)
    c.setStrokeColor(BORDER)
    c.setLineWidth(0.8)
    c.rect(left, panel_bottom, right - left, panel_height, fill=1, stroke=1)
    c.setFillColor(GOLD)
    c.rect(left, panel_bottom, 3.2 * mm, panel_height, fill=1, stroke=0)

    x = left + 8 * mm
    y = y_top - 7.2 * mm
    c.setFillColor(INK)
    c.setFont("Helvetica-Bold", 7.8)
    c.drawString(x, y, "Date:")
    c.setFont("Helvetica", 7.8)
    c.drawString(x + 12 * mm, y, payload.document_date)

    c.setFont("Helvetica-Bold", 7.8)
    c.drawRightString(right - 31 * mm, y, "Reference:")
    c.setFont("Helvetica", 7.8)
    c.drawRightString(right - 5 * mm, y, payload.reference)

    y -= 5.4 * mm
    c.setFont("Helvetica-Bold", 7.8)
    c.drawString(x, y, "To:")
    c.setFont("Helvetica-Bold", 8.2)
    c.drawString(x + 12 * mm, y, payload.recipient_name)

    y -= 4.9 * mm
    c.setFont("Helvetica", 7.7)
    c.drawString(x + 12 * mm, y, payload.recipient_company)
    for address_line in payload.recipient_address.splitlines()[:2]:
        if address_line.strip():
            y -= 4.4 * mm
            c.drawString(x + 12 * mm, y, address_line.strip())

    details: list[str] = []
    if payload.recipient_phone.strip():
        details.append(f"Tel: {payload.recipient_phone.strip()}")
    if payload.recipient_email.strip():
        details.append(f"Email: {payload.recipient_email.strip()}")
    if details:
        c.setFont("Helvetica", 7.2)
        c.setFillColor(MUTED)
        c.drawRightString(right - 5 * mm, panel_bottom + 5 * mm, "   |   ".join(details))

    return panel_bottom


