def _draw_signature_panel(
    c: canvas.Canvas,
    payload: LetterheadDocument,
    y_top: float,
) -> tuple[float, tuple[float, float, float, float] | None]:
    width, _ = A4
    left = 18 * mm
    right = width - 18 * mm
    panel_height = 46 * mm
    panel_bottom = y_top - panel_height

    c.setFillColor(PALE_WARM)
    c.setStrokeColor(GOLD)
    c.setLineWidth(0.9)
    c.rect(left, panel_bottom, right - left, panel_height, fill=1, stroke=1)

    x = left + 7 * mm
    y = y_top - 9 * mm
    c.setFillColor(NAVY_DARK)
    c.setFont("Helvetica-Bold", 9.2)
    c.drawString(x, y, payload.signatory_name)
    y -= 5.2 * mm
    c.setFillColor(INK)
    c.setFont("Helvetica-Bold", 7.5)
    c.drawString(x, y, payload.signatory_title)
    y -= 4.7 * mm
    c.setFillColor(MUTED)
    c.setFont("Helvetica", 7.1)
    c.drawString(x, y, payload.signatory_contact)

    field_left = x
    field_bottom = panel_bottom + 7.5 * mm
    field_width = 77 * mm
    field_height = 12.5 * mm
    signature_rect: tuple[float, float, float, float] | None = None

    c.setFillColor(NAVY)
    c.setFont("Helvetica-Bold", 5.8)
    c.drawString(field_left, field_bottom + field_height + 2.2 * mm, "AUTHORISED SIGNATURE")
    if payload.include_signature_field:
        c.setFillColor(white)
        c.setStrokeColor(NAVY)
        c.setLineWidth(0.75)
        c.rect(field_left, field_bottom, field_width, field_height, fill=1, stroke=1)
        c.setFillColor(MUTED)
        c.setFont("Helvetica", 6.1)
        c.drawString(
            field_left + 3 * mm,
            field_bottom + 4.4 * mm,
            "Click in this field to apply a certificate-based digital signature",
        )
        signature_rect = (
            field_left,
            field_bottom,
            field_left + field_width,
            field_bottom + field_height,
        )
    else:
        c.setStrokeColor(NAVY)
        c.line(field_left, field_bottom, field_left + field_width, field_bottom)

    date_x = field_left + field_width + 8 * mm
    c.setFillColor(NAVY)
    c.setFont("Helvetica-Bold", 5.8)
    c.drawString(date_x, field_bottom + field_height + 2.2 * mm, "DATE SIGNED")
    c.setStrokeColor(NAVY)
    c.line(date_x, field_bottom, date_x + 34 * mm, field_bottom)

    if payload.include_document_stamp:
        _draw_document_stamp(c, right - 23 * mm, panel_bottom + panel_height / 2)

    return panel_bottom, signature_rect


def _build_base_pdf(
    payload: LetterheadDocument,
) -> tuple[bytes, int, tuple[float, float, float, float] | None]:
    buffer = BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    left = 18 * mm
    right = width - 18 * mm
    max_width = right - left
    page_number = 1
    y = height - 61 * mm

    def new_page() -> None:
        nonlocal page_number, y
        c.showPage()
        page_number += 1
        _draw_letterhead(c, page_number, payload.document_title)
        y = height - 61 * mm

    _draw_letterhead(c, page_number, payload.document_title)
    y = _draw_recipient_panel(c, payload, y)
    y -= 9 * mm

    c.setFillColor(NAVY)
    c.setFont("Helvetica-Bold", 9.4)
    subject = f"RE: {payload.subject.upper()}"
    for line in _wrap_line(subject, "Helvetica-Bold", 9.4, max_width):
        c.drawString(left, y, line)
        y -= 5.2 * mm

    y -= 1.5 * mm
    c.setFillColor(INK)
    c.setFont("Helvetica", 9.4)
    for paragraph in payload.body.replace("\r\n", "\n").split("\n"):
        if not paragraph.strip():
            y -= 4 * mm
            continue
        for line in _wrap_line(paragraph.strip(), "Helvetica", 9.4, max_width):
            if y < 74 * mm:
                new_page()
                c.setFillColor(INK)
                c.setFont("Helvetica", 9.4)
            c.drawString(left, y, line)
            y -= 4.8 * mm
        y -= 1.2 * mm

    if y < 78 * mm:
        new_page()

    y -= 4 * mm
    c.setFillColor(INK)
    c.setFont("Helvetica", 9.2)
    c.drawString(left, y, "Yours faithfully,")
    y -= 7 * mm

    _, signature_rect = _draw_signature_panel(c, payload, y)
    signature_page_index = page_number - 1

    c.save()
    buffer.seek(0)
    return buffer.getvalue(), signature_page_index, signature_rect


def _add_signature_field(
    pdf_bytes: bytes,
    page_index: int,
    rect: tuple[float, float, float, float],
) -> bytes:
    reader = PdfReader(BytesIO(pdf_bytes))
    writer = PdfWriter()
    writer.append_pages_from_reader(reader)
    page = writer.pages[page_index]

    signature = DictionaryObject(
        {
            NameObject("/FT"): NameObject("/Sig"),
            NameObject("/Type"): NameObject("/Annot"),
            NameObject("/Subtype"): NameObject("/Widget"),
            NameObject("/T"): TextStringObject("signature"),
            NameObject("/TU"): TextStringObject("Authorised digital signature"),
            NameObject("/F"): NumberObject(4),
            NameObject("/Rect"): ArrayObject([FloatObject(value) for value in rect]),
            NameObject("/P"): page.indirect_reference,
        }
    )
    signature_ref = writer._add_object(signature)
    annotations = page.get("/Annots")
    if annotations is None:
        annotations = ArrayObject()
        page[NameObject("/Annots")] = annotations
    annotations.append(signature_ref)

    acro_form = DictionaryObject(
        {
            NameObject("/Fields"): ArrayObject([signature_ref]),
            NameObject("/SigFlags"): NumberObject(3),
            NameObject("/NeedAppearances"): BooleanObject(False),
        }
    )
    writer._root_object[NameObject("/AcroForm")] = writer._add_object(acro_form)
    writer.add_metadata(
        {
            "/Title": "Guardrisk Document Studio Letter",
            "/Author": "Guardrisk Insurance Brokers",
            "/Creator": "gRisk Document Studio",
        }
    )

    output = BytesIO()
    writer.write(output)
    return output.getvalue()


def render_letterhead_pdf(payload: LetterheadDocument) -> bytes:
    base, signature_page, signature_rect = _build_base_pdf(payload)
    if not payload.include_signature_field or signature_rect is None:
        return base
    return _add_signature_field(base, signature_page, signature_rect)


def _filename(subject: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9]+", "-", subject).strip("-").lower()
    return f"{cleaned[:70] or 'guardrisk-letter'}.pdf"


@router.post("/render")
async def render_document(
    payload: LetterheadDocument,
    request: Request,
    user: CurrentUser,
    session: DbSession,
) -> StreamingResponse:
    pdf_bytes = render_letterhead_pdf(payload)
    await record_audit_event(
        session,
        action="document_studio.generated",
        entity_type="generated_document",
        entity_id=payload.reference,
        actor_user_id=user.id,
        details={
            "document_title": payload.document_title,
            "subject": payload.subject,
            "reference": payload.reference,
            "signature_field": payload.include_signature_field,
            "document_stamp": payload.include_document_stamp,
        },
        ip_address=request.client.host if request.client else None,
    )
    await session.commit()
    filename = _filename(payload.subject)
    return StreamingResponse(
        BytesIO(pdf_bytes),
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
